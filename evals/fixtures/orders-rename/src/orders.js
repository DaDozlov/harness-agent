const bySku = new Map(CATALOG.map((product) => [product.sku, product]));

/** Looks a product up; throws for an unknown SKU. */
export function product(sku) {
  const found = bySku.get(sku);
  if (!found) throw new RangeError(`Unknown SKU: ${sku}`);
  return found;
}

/**
 * A new order. `customerName` is who ordered; `lines` are `{ sku, quantity }`.
 */
export function createOrder({ id, customerName, city, lines }) {
  if (!customerName || !customerName.trim()) throw new RangeError('An order needs a customer name.');
  if (!lines.length) throw new RangeError('An order needs at least one line.');
  const items = lines.map(({ sku, quantity }) => {
    if (!Number.isInteger(quantity) || quantity < 1) throw new RangeError(`Bad quantity for ${sku}`);
    const { name, priceCents, weightGrams } = product(sku);
    return { sku, name, quantity, priceCents, weightGrams };
  });
  return { id, customerName: customerName.trim(), city, items, status: 'open' };
}

/** The sum of the order's lines, in cents. */
export function orderTotal(order) {
  return order.items.reduce((sum, item) => sum + item.priceCents * item.quantity, 0);
}

/** The order's weight in grams, for shipping. */
export function orderWeight(order) {
  return order.items.reduce((sum, item) => sum + item.weightGrams * item.quantity, 0);
}

/** A one-line summary for lists: who, how many items, how much. */
export function summarize(order) {
  const count = order.items.reduce((sum, item) => sum + item.quantity, 0);
  return `#${order.id} ${order.customerName}: ${count} items, ${(orderTotal(order) / 100).toFixed(2)} EUR`;
}
