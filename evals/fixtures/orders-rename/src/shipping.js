const zoneByPostcode = new Map(ZONES.map(([postcode, , zone]) => [postcode, zone]));

/** Shipping cost in cents: by zone, and by weight above 2 kg. */
export function shippingCents(order, postcode) {
  const zone = zoneByPostcode.get(postcode);
  if (!zone) throw new RangeError(`We do not deliver to ${postcode}`);
  const extraKilos = Math.max(0, Math.ceil((orderWeight(order) - 2000) / 1000));
  return 390 + (zone - 1) * 150 + extraKilos * 120;
}

/** The address label: the customer's name, then the city. */
export function label(order, postcode) {
  const { customerName, city } = order;
  return [customerName.toUpperCase(), `${postcode} ${city}`].join('\n');
}
